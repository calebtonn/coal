// Compile the Intent Manifest schema into a standalone validator module, so the UI never calls
// new Function at runtime and the daemon's CSP can omit 'unsafe-eval'. Run by prebuild and pretest.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone';

export const SCHEMA_PATH = new URL('../../spec/intent-manifest.schema.json', import.meta.url);
export const OUTPUT_PATH = new URL('../src/generated/validate-manifest.js', import.meta.url);

export function generateValidatorSource(schemaText = readFileSync(SCHEMA_PATH, 'utf8')): string {
  const ajv = new Ajv2020({ strict: false, code: { source: true, esm: true } });
  addFormats(ajv);
  let code = standaloneCode(ajv, ajv.compile(JSON.parse(schemaText)));
  // Ajv's ESM output still calls require() for its runtime helpers; turn those into imports.
  const imports: string[] = [];
  code = code.replace(/require\("([^"]+)"\)/g, (_, spec: string) => {
    let i = imports.indexOf(spec);
    if (i < 0) i = imports.push(spec) - 1;
    return `__dep${i}`;
  });
  // Bundlers expose a CommonJS module's exports as the namespace; Node puts them on .default.
  const header = imports
    .map((spec, i) => `import * as __ns${i} from "${spec}";\nconst __dep${i} = __ns${i}.default?.__esModule ? __ns${i}.default : __ns${i};`)
    .join('\n');
  return `// Generated by web/scripts/gen-validator.ts from spec/intent-manifest.schema.json. Do not edit.\n${header}\n${code.replace(/^"use strict";/, '')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT_PATH, generateValidatorSource());
  console.log(`wrote ${OUTPUT_PATH.pathname}`);
}
